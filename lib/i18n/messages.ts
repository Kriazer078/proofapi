export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

const INTL: Record<Locale, string> = { en: "en-GB", ru: "ru-RU", kk: "kk-KZ" };

const KK_MONTHS = ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан", "қараша", "желтоқсан"];

export function formatDate(unixSeconds: number, locale: Locale): string {
  const d = new Date(unixSeconds * 1000);
  // Browsers ship little Kazakh date data, so this one is spelled out by hand.
  if (locale === "kk") {
    const time = `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
    return `${d.getFullYear()} ж. ${d.getDate()} ${KK_MONTHS[d.getMonth()]}, ${time}`;
  }
  return new Intl.DateTimeFormat(INTL[locale], {
    day: "numeric",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(d);
}
